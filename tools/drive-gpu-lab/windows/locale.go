func localeCode(s string) string {
	s = strings.TrimSpace(strings.ToLower(s))
	if s == "" || s == "c" || strings.HasPrefix(s, "c.") || s == "posix" {
		return ""
	}
	s = strings.Split(s, ":")[0]
	s = strings.Split(s, ".")[0]
	s = strings.ReplaceAll(s, "_", "-")
	s = strings.Split(s, "-")[0]
	if s == "iw" {
		s = "he"
	}
	if s == "in" {
		s = "id"
	}
	if _, ok := translations[s]; ok {
		return s
	}
	return ""
}

func detectLocale(override, wineLocale, envLCAll, envLanguage, envLang string) string {
	if override == "auto" || override == "" {
		for _, s := range []string{envLCAll, envLanguage, envLang, wineLocale} {
			if c := localeCode(s); c != "" {
				return c
			}
		}
		return "en"
	}
	if c := localeCode(override); c != "" {
		return c
	}
	return "en"
}

func localize(lang, key string) string {
	if p, ok := translations[lang]; ok {
		if v := p.Labels[key]; v != "" {
			return v
		}
	}
	if v := translations["en"].Labels[key]; v != "" {
		return v
	}
	return key
}

func isRTL(lang string) bool { return translations[lang].RTL }

func languageName(lang string) string {
	if lang == "auto" {
		return "AUTO"
	}
	if p, ok := translations[lang]; ok {
		return p.Name
	}
	return "English"
}
